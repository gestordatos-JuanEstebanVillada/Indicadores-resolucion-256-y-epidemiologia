-- Roles específicos del portal de Indicadores (no modifica INTRANET_USUARIOS)

CREATE TABLE INTRANET_CALIDAD_ROLES (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USUARIO_ID NUMBER NOT NULL,
    ROL VARCHAR2(50) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UQ_CALIDAD_USUARIO_ROL UNIQUE (USUARIO_ID)
);

COMMENT ON TABLE INTRANET_CALIDAD_ROLES IS
  'Asignación de roles del sistema Indicadores; USUARIO_ID = INTRANET_USUARIOS.ID';
COMMENT ON COLUMN INTRANET_CALIDAD_ROLES.ROL IS
  'ADMIN | RESOLUCION_256 | EPIDEMIOLOGIA';

