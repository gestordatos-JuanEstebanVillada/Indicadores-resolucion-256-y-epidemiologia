-- Catálogo de áreas / módulos de indicadores (codigo = valor en INTRANET_CALIDAD.MODULO)

CREATE TABLE INTRANET_MODULOS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CODIGO VARCHAR2(50) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ICONO VARCHAR2(50),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UQ_INTRANET_MODULO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT UQ_INTRANET_MODULO_NOMBRE UNIQUE (NOMBRE)
);

COMMENT ON TABLE INTRANET_MODULOS IS 'Áreas de indicadores; CODIGO se guarda en INTRANET_CALIDAD.MODULO';
COMMENT ON COLUMN INTRANET_MODULOS.CODIGO IS 'Identificador estable (ej. RESOLUCION_256, URGENCIAS)';
COMMENT ON COLUMN INTRANET_MODULOS.NOMBRE IS 'Etiqueta visible en menú';
COMMENT ON COLUMN INTRANET_MODULOS.ICONO IS 'Nombre Lucide o emoji';

