-- Limpieza y datos RBAC (ejecutar manualmente en Oracle como dueño del esquema BDLIGA).
-- Mapeo: ROL = jerarquía | NOMBRE_ROL = EDITOR|LECTOR | MODULO = código de área
-- NO usa Alembic; no crea tablas nuevas excepto columnas opcionales si faltan.

-- 0) Asegurar columna NOMBRE_ROL (si ya existe, ignorar ORA-01430)
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE INTRANET_CALIDAD_ROLES ADD (NOMBRE_ROL VARCHAR2(50))';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1430, -942) THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE INTRANET_CALIDAD_ROLES ADD (MODULO VARCHAR2(100))';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1430, -942) THEN RAISE; END IF;
END;
/

-- 1) Quitar UNIQUE (USUARIO_ID, ROL) si impide varias filas por usuario
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE INTRANET_CALIDAD_ROLES DROP CONSTRAINT UQ_CALIDAD_USUARIO_ROL';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE NOT IN (-2443, -942) THEN RAISE; END IF;
END;
/

-- 2) Limpiar datos sucios
DELETE FROM INTRANET_CALIDAD_ROLES;
COMMIT;

-- 3) Admin global (ID 0): una fila sin módulo
INSERT INTO INTRANET_CALIDAD_ROLES (USUARIO_ID, ROL, NOMBRE_ROL, MODULO)
