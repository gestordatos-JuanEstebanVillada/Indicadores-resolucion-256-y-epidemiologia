CREATE TABLE INTRANET_CALIDAD_AUDITORIA (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    USUARIO VARCHAR2(250) NOT NULL,
    ACCION VARCHAR2(50) NOT NULL,
    MODULO VARCHAR2(100) NOT NULL,
    DETALLE CLOB NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

COMMENT ON TABLE INTRANET_CALIDAD_AUDITORIA IS
  'Historial de acciones en el portal Indicadores (POST, PUT, DELETE)';
