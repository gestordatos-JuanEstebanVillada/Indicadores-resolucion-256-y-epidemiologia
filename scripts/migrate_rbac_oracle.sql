-- Migración RBAC: esquema legado (columna ROL) → NOMBRE_ROL + MODULO + INTRANET_SISTEMA_ROLES
-- Ejecutar una vez en SQL Developer como el esquema dueño de las tablas.
-- Ajuste nombres si sus tablas no van entre comillas dobles.

-- 1) Catálogo de roles de sistema
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE INTRANET_SISTEMA_ROLES (
            NOMBRE_ROL VARCHAR2(50) PRIMARY KEY,
            ES_ADMIN_GLOBAL NUMBER(1) DEFAULT 0 NOT NULL,
            PERMITE_EDICION NUMBER(1) DEFAULT 0 NOT NULL
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

MERGE INTO INTRANET_SISTEMA_ROLES t
USING (
    SELECT 'ADMINISTRADOR' AS NOMBRE_ROL, 1 AS ES_ADMIN_GLOBAL, 1 AS PERMITE_EDICION FROM dual UNION ALL
    SELECT 'ADMINISTRADOR_AREA', 0, 1 FROM dual UNION ALL
    SELECT 'LECTOR', 0, 0 FROM dual
) s
ON (t.NOMBRE_ROL = s.NOMBRE_ROL)
WHEN NOT MATCHED THEN
    INSERT (NOMBRE_ROL, ES_ADMIN_GLOBAL, PERMITE_EDICION)
    VALUES (s.NOMBRE_ROL, s.ES_ADMIN_GLOBAL, s.PERMITE_EDICION);

-- 2) Nuevas columnas en INTRANET_CALIDAD_ROLES (si aún no existen)
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE INTRANET_CALIDAD_ROLES ADD (NOMBRE_ROL VARCHAR2(50))';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1430, -942) THEN RAISE; END IF;
END;
/
BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE INTRANET_CALIDAD_ROLES ADD (MODULO VARCHAR2(50))';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE NOT IN (-1430, -942) THEN RAISE; END IF;
END;
/

-- 3) Copiar datos desde ROL (solo filas sin NOMBRE_ROL)
UPDATE INTRANET_CALIDAD_ROLES
SET
    NOMBRE_ROL = CASE WHEN UPPER(TRIM(ROL)) = 'ADMIN' THEN 'ADMINISTRADOR' ELSE 'ADMINISTRADOR_AREA' END,
    MODULO = CASE WHEN UPPER(TRIM(ROL)) = 'ADMIN' THEN NULL ELSE UPPER(TRIM(ROL)) END
WHERE NOMBRE_ROL IS NULL;

COMMIT;

