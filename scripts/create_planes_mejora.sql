CREATE TABLE INTRANET_PLANES_MEJORA (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CALIDAD_ID NUMBER NOT NULL,
    MODULO VARCHAR2(50) NOT NULL,
    YEAR NUMBER(4) NOT NULL,
    MES NUMBER(2) NOT NULL,
    VALOR_OBTENIDO NUMBER(18,6),
    META_INSTITUCIONAL VARCHAR2(4000),
    OBSERVACIONES CLOB NOT NULL,
    RESPONSABLE_NOMBRE VARCHAR2(250) NOT NULL,
    RESPONSABLE_CORREO VARCHAR2(250) NOT NULL,
    FECHA_CUMPLIMIENTO DATE NOT NULL,
    ESTADO VARCHAR2(50) DEFAULT 'PENDIENTE',
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_PLAN_CALIDAD FOREIGN KEY (CALIDAD_ID) REFERENCES INTRANET_CALIDAD(ID) ON DELETE CASCADE,
    CONSTRAINT CK_PLAN_MES CHECK (MES BETWEEN 1 AND 12)
);

CREATE INDEX IX_PLANES_MEJORA_CALIDAD_MES ON INTRANET_PLANES_MEJORA (CALIDAD_ID, YEAR, MES);
ALTER TABLE INTRANET_PLANES_MEJORA ADD ESTADO VARCHAR2(50) DEFAULT 'PENDIENTE';
